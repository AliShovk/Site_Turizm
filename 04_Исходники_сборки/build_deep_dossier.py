# --- фото только для Эдельвейса (единственные доступные публично)
def b64(paths, width=640):
    out = []
    for p in paths:
        try:
            im = Image.open(p).convert("RGB")
        except Exception:
            continue
        w, h = im.size
        if w > width:
            im = im.resize((width, int(h * width / w)), Image.LANCZOS)
        buf = io.BytesIO()
        im.save(buf, "JPEG", quality=76, optimize=True)
        out.append(base64.b64encode(buf.getvalue()).decode())
    return out


